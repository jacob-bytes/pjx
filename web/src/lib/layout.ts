/**
 * 表格滚动区的公共类。
 *
 * 背景：四个页面（总览 / 探测 / 告警两个 tab）都把表格放进一个
 * "填满视口剩余高度、内部滚动、表头吸顶"的容器里，写法是
 * `max-h-[calc(100svh-Npx)]`。原来四处都写死 `11rem`(176px) ——
 * 那是**加 KPI 卡片之前**的口径。
 *
 * 实测（把上方内容高度加总）：
 *
 * | 视口 | 表格区 top | 组成 |
 * | --- | --- | --- |
 * | ≥1280 | 221px | 顶栏 48 + 上边距 16 + KPI 83 + 12 + 工具栏 50 + 12 |
 * | 1024–1279 | 313px | 同上，但 KPI 转 3 列变 2 行（175） |
 * | 640–1023 | 353px | 再叠加工具栏换行到 2 行（90） |
 * | <640 | 486px | KPI 2 列 3 行（268）+ 工具栏 3 行（130） |
 *
 * 常数偏小 → 容器比"视口剩余"高，行数一多（真实数据 200 台）容器的底部就会
 * 掉到视口外面：1280 下 45px、768 下 177px、390 下 310px。
 * 本机 12 行看不出问题（内容只有 633px，根本没触发 max-h），所以一直没暴露。
 *
 * 现在按实测四档取值。这是"魔法数"的务实版本：真正干净的做法是让外壳成为
 * 定高 flex 列、表格区 `flex-1 min-h-0`，但那要动 app-shell 与四个页面的结构，
 * 属于独立一轮。
 */
export const TABLE_SCROLLER =
  "-mx-5 max-h-[calc(100svh-30.4rem)] overflow-auto px-5 sm:max-h-[calc(100svh-22rem)] lg:max-h-[calc(100svh-19.5rem)] xl:max-h-[calc(100svh-13.8rem)]"
